export type Key = keyof (typeof dict)["cs"];

export async function getLocale(): Promise<Locale> {
  const c = (await cookies()).get("lang")?.value;
  return (LOCALES as readonly string[]).includes(c ?? "") ? (c as Locale) : "cs";
}

export async function getT() {
  const locale = await getLocale();
  const t = (key: Key) => dict[locale][key] as string;
  return { t, locale };
}

export function dateFmt(locale: Locale, d: Date) {
  const tag = locale === "cs" ? "cs-CZ" : locale === "sk" ? "sk-SK" : "en-GB";
  return new Intl.DateTimeFormat(tag, { dateStyle: "medium", timeStyle: "short", timeZone: "Europe/Prague" }).format(d);
}
